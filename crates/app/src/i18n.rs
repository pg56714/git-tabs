//! Interface language. The source strings are Traditional Chinese; `t` / `tr` swap in the
//! English text from the table below when the language is English.
//!
//! The language is "auto" (follow the system), "zh-TW" or "en"; see `set_from_setting`.

use std::collections::HashMap;
use std::sync::OnceLock;
use std::sync::atomic::{AtomicBool, Ordering};

static ENGLISH: AtomicBool = AtomicBool::new(false);

pub fn is_en() -> bool {
    ENGLISH.load(Ordering::Relaxed)
}

/// What the system language says: Chinese variants get Traditional Chinese, everything else English.
pub fn detect() -> bool {
    sys_locale::get_locale().map(|l| !l.to_lowercase().starts_with("zh")).unwrap_or(false)
}

/// `setting` is "auto", "zh-TW" or "en".
pub fn set_from_setting(setting: &str) {
    let en = match setting {
        "en" => true,
        "zh-TW" => false,
        _ => detect(),
    };
    ENGLISH.store(en, Ordering::Relaxed);
}

fn table() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| TABLE.iter().copied().collect())
}

/// The text in the current language.
pub fn t(s: &'static str) -> &'static str {
    if is_en() { table().get(s).copied().unwrap_or(s) } else { s }
}

/// A template with `{name}` and `{}` holes, translated and filled.
pub fn tr(tmpl: &'static str, named: &[(&str, String)], pos: &[String]) -> String {
    let src = t(tmpl);
    let mut out = String::with_capacity(src.len() + 16);
    let mut next = 0usize;
    let mut chars = src.char_indices().peekable();
    while let Some((i, c)) = chars.next() {
        if c != '{' {
            out.push(c);
            continue;
        }
        let Some(end) = src[i..].find('}') else {
            out.push(c);
            continue;
        };
        let name = &src[i + 1..i + end];
        if name.is_empty() {
            out.push_str(pos.get(next).map(String::as_str).unwrap_or(""));
            next += 1;
        } else if let Some((_, v)) = named.iter().find(|(k, _)| *k == name) {
            out.push_str(v);
        } else {
            out.push_str(&src[i..=i + end]);
        }
        while chars.peek().is_some_and(|(j, _)| *j <= i + end) {
            chars.next();
        }
    }
    out
}

